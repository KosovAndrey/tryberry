// ══ Версии по маркетплейсам ═════════════════════════════════════════════════
//
// Те же кадры, отличается ровно площадка. Тот iPhone продавал ОДИН продавец и
// выставил ту же цену на WB, Ozon и Я.Маркете — не было её только на AliExpress
// (владелец, 2026-08-08), поэтому и цена, и история правдивы для всех трёх.
//
// ⚠️ Тайминги не трогать: они подогнаны под записанную озвучку. Массив `times`
// идёт по индексу сообщения, длина обязана совпадать — иначе часть шапок молча
// останется от базовой версии, и заметно это только покадрово на рендере.
// На этот случай проверка ниже падает при расхождении.

const withMarketplace = (
  base: ChatData,
  m: {url: string; label: string; times: string[]},
): ChatData => ({
  ...base,
  messages: base.messages.map((msg, i, all) => {
    if (m.times.length !== all.length) {
      throw new Error(
        `withMarketplace(${m.label}): времён ${m.times.length}, сообщений ${all.length}`,
      );
    }
    if (msg.kind === 'daybreak') return msg;
    const time = m.times[i] || msg.time;
    if (msg.kind === 'text' && msg.from === 'user') return {...msg, time, text: m.url};
    if (msg.kind === 'text') return {...msg, time, text: msg.text.replace(/· Ozon$/, `· ${m.label}`)};
    if (msg.kind === 'chart') {
      return {...msg, time, note: msg.note?.replace(/· Ozon$/, `· ${m.label}`)};
    }
    return {...msg, time};
  }),
});

