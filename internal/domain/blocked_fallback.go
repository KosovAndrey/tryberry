package domain

import (
	"fmt"
	"time"
)

// BlockedFallbackText — что отвечать пользователю, когда площадка отказалась
// отдавать товар. Раньше во всех каналах было глухое «❌ Не удалось получить
// данные о товаре» — и это неправда дважды: отказ временный, а по знакомому
// товару у нас есть история цен, которую можно показать прямо сейчас.
//
// Текст общий для Telegram/VK/MAX, поэтому без разметки: HTML-канал оборачивает
// сам. lastPrice<=0 или нулевой lastAt — товар нам не знаком, отдаём только
// статус площадки.
//
// Возраст цены печатаем ВСЕГДА, когда её показываем: цифра без «когда» выдаёт
// себя за текущую, а это ровно то враньё, от которого продукт защищает.
func BlockedFallbackText(marketplace, productName string, lastPrice float64, lastAt, now time.Time) string {
	head := fmt.Sprintf("⚠️ %s сейчас не отдаёт данные — это временно.", marketplace)
	if lastPrice <= 0 || lastAt.IsZero() {
		return head + "\n\nПопробуй ещё раз через несколько минут: обычно проходит само."
	}
	name := productName
	if name == "" {
		name = "Этот товар"
	}
	return fmt.Sprintf(
		"%s\n\nВот что я знаю по своей истории:\n\n%s\n💰 Последняя известная цена: %s (%s)\n\n"+
			"Повтори ссылку через несколько минут — как только площадка ответит, добавлю в отслеживание.",
		head, name, FormatPrice(lastPrice), HumanizeAge(now.Sub(lastAt)),
	)
}
